#!/bin/bash

# Exit immediately if any command fails (don't continue with broken state)
set -e

# Terminal colors for readable output
GREEN="\033[32m"
RED="\033[31m"
RESET="\033[0m"

# ── Step 1: Install prerequisites ────────────────────────────────────────────
# -qq = quiet mode (less output), 2>/dev/null = hide stderr warnings
echo "Installing dependencies..."
apt-get update -qq 2>/dev/null
apt-get install -y -qq curl net-tools 2>/dev/null
echo -e "${GREEN}Prerequisites OK${RESET}"

# ── Step 2: Detect the network interface for flannel ─────────────────────────
# The VM has multiple network interfaces:
#   - eth0 / enp0s3: NAT (Vagrant default, can reach internet but isolated)
#   - eth1 / enp0s8: Private network (192.168.56.110, set in Vagrantfile)
#
# WHAT IS FLANNEL?
# Every pod in Kubernetes gets its own virtual IP (like 10.42.0.5). But pods
# aren't real machines — they're just processes. Flannel is the networking
# plugin (CNI = Container Network Interface) that creates and manages this
# virtual pod network. It builds an overlay network on top of a real interface.
#
# WHY --flannel-iface?
# Flannel needs a real network interface as its "backbone." If we don't
# specify one, it might pick the NAT interface (eth0), and inter-node or
# host-to-pod traffic would break. We point it at the private network
# interface (the one with 192.168.56.110) so all pod traffic goes through
# the right network.
#
# This command: finds the interface name that has IP 192.168.56.110 assigned.
# If detection fails, falls back to "eth1" (the typical name).
FLANNEL_IFACE=$(ip -o -4 addr list | grep 192.168.56.110 | awk '{print $2}' | head -1)
if [ -z "$FLANNEL_IFACE" ]; then
  FLANNEL_IFACE="eth1"
  echo "Could not detect interface, using $FLANNEL_IFACE"
else
  echo "Using interface $FLANNEL_IFACE for flannel"
fi

# ── Step 3: Install K3s in server mode ───────────────────────────────────────
# Downloads and runs the K3s install script from https://get.k3s.io
# "server" = control plane (API server + scheduler + controller + etcd + kubelet)
#
# In Part 1 there were 2 VMs (server + agent). Here we only have 1 VM that
# does BOTH roles: it's the control plane AND runs the application pods.
echo "Installing K3s server..."
curl -sfL https://get.k3s.io | sh -s - server \
  --write-kubeconfig-mode 644 \
  --tls-san="$(hostname)" \
  --tls-san="192.168.56.110" \
  --node-ip=192.168.56.110 \
  --bind-address=192.168.56.110 \
  --advertise-address=192.168.56.110 \
  --flannel-iface="$FLANNEL_IFACE"
# Flags explained (same as Part 1, see docs/02-part1.md for details):
#   --write-kubeconfig-mode 644  : kubeconfig readable by non-root users
#   --tls-san="$(hostname)"      : add VM hostname to TLS cert
#   --tls-san="192.168.56.110"   : add VM IP to TLS cert (for host kubectl)
#   --node-ip                    : use private network IP for cluster comms
#   --bind-address               : API server listens on this IP
#   --advertise-address          : tell agents to reach server at this IP
#   --flannel-iface              : flannel uses this interface for pod networking

# Path to the kubeconfig file generated by K3s
KUBECONFIG=/etc/rancher/k3s/k3s.yaml

# ── Step 4: Wait for K3s to be ready ────────────────────────────────────────
# The node takes a few seconds to initialize. We loop until `kubectl get nodes`
# shows "Ready" status. Without this wait, applying manifests would fail.
echo "Waiting for K3s to be ready..."
until kubectl --kubeconfig="$KUBECONFIG" get nodes 2>/dev/null | grep -q Ready; do
  sleep 5
done
echo -e "${GREEN}K3s is ready${RESET}"

# ── Step 5: Wait for Traefik ────────────────────────────────────────────────
# K3s automatically deploys Traefik as the default ingress controller.
# Traefik runs as a pod in the kube-system namespace. We wait for it because
# our Ingress resource (ingress.yaml) needs Traefik to be running to work.
# The label selector "app.kubernetes.io/name=traefik" finds the Traefik pod.
echo "Waiting for Traefik ingress controller..."
until kubectl --kubeconfig="$KUBECONFIG" get pods -n kube-system -l app.kubernetes.io/name=traefik 2>/dev/null | grep -q Running; do
  sleep 5
done
echo -e "${GREEN}Traefik is ready${RESET}"

# ── Step 6: Copy kubeconfig to host ─────────────────────────────────────────
# Copy the kubeconfig to /vagrant (= p2/ on your Mac via synced folder).
# This lets you run kubectl from your Mac, not just from inside the VM.
cp "$KUBECONFIG" /vagrant/k3s.yaml
chmod 644 /vagrant/k3s.yaml

# Inside the VM, the API server is at 127.0.0.1 (localhost).
# From your Mac, you need to reach it at 192.168.56.110 (the VM's private IP).
# This sed command rewrites the server address in the copied kubeconfig.
sed -i 's/127.0.0.1/192.168.56.110/g' /vagrant/k3s.yaml

# ── Step 7: Deploy applications and Ingress ─────────────────────────────────
# kubectl apply -f: reads a YAML file and creates/updates the resources in it.
# /vagrant/confs/ = p2/confs/ on your Mac (synced folder).
echo "Deploying apps..."
kubectl --kubeconfig="$KUBECONFIG" apply -f /vagrant/confs/apps.yaml

echo "Deploying Ingress..."
kubectl --kubeconfig="$KUBECONFIG" apply -f /vagrant/confs/ingress.yaml

echo -e "${GREEN}Part 2 bootstrap complete!${RESET}"
echo ""
echo "Test from host (use a regular terminal):"
echo "  curl -H 'Host: app1.com' http://192.168.56.110"
echo "  curl -H 'Host: app2.com' http://192.168.56.110"
echo "  curl http://192.168.56.110"
